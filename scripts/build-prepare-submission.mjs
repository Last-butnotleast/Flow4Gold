import { readFile, writeFile } from 'node:fs/promises';
import { isDeepStrictEqual } from 'node:util';
import { format, resolveConfig } from 'prettier';
import {
  TypeScriptParser,
  WorkflowBuilder,
  JsonToAstParser,
  AstToTypeScriptGenerator,
} from '@n8n-as-code/transformer';
export const workflowPath = 'workflows/flow4gold/tasks/competition/prepare-submission.workflow.ts';
export async function buildSource() {
  const formatting = (await resolveConfig('scripts/build-core.mjs')) ?? {};
  const validator = (await readFile('shared/machine-validation.mjs', 'utf8')).replace(
    /export function /g,
    'function ',
  );
  const invocation = await format(
    await readFile('runtime/prepare-submission-invocation.js', 'utf8'),
    { ...formatting, parser: 'babel' },
  );
  const result = await format(
    validator + '\n' + (await readFile('runtime/prepare-submission-result.js', 'utf8')),
    { ...formatting, parser: 'babel' },
  );
  const nodes = [],
    routes = [];
  const node = (property, name, type, version, position, parameters, metadata = {}) =>
    nodes.push(
      `@node(${JSON.stringify({ id: `prepare-submission-${property}`, name, type: `n8n-nodes-base.${type}`, version, position, ...metadata })})\n${property}=${JSON.stringify(parameters)};`,
    );
  node('ReceiveInvocation', 'Receive Task Invocation', 'executeWorkflowTrigger', 1.2, [0, 0], {
    inputSource: 'passthrough',
  });
  node('ValidateInvocation', 'Validate Invocation', 'code', 2, [240, 0], {
    mode: 'runOnceForAllItems',
    jsCode: invocation,
  });
  node(
    'ReadCaseEvents',
    'Read Case Events',
    'dataTable',
    1.1,
    [480, 0],
    {
      resource: 'row',
      operation: 'get',
      dataTableId: { __rl: true, value: 'TjuB58skTvPRCwB3', mode: 'id' },
      filters: {
        conditions: [
          {
            keyName: 'caseId',
            condition: 'eq',
            keyValue: "={{ $('Validate Invocation').first().json.caseId }}",
          },
        ],
      },
      returnAll: true,
    },
    { alwaysOutputData: true },
  );
  node(
    'ReadDefinition',
    'Read Pinned Definition',
    'dataTable',
    1.1,
    [720, 0],
    {
      resource: 'row',
      operation: 'get',
      dataTableId: { __rl: true, value: 'Lm8JZL9uCNqj14vE', mode: 'id' },
      matchType: 'allConditions',
      filters: {
        conditions: [
          {
            keyName: 'machine',
            condition: 'eq',
            keyValue: "={{ $('Validate Invocation').first().json.machine }}",
          },
          {
            keyName: 'version',
            condition: 'eq',
            keyValue: "={{ $('Validate Invocation').first().json.machineVersion }}",
          },
        ],
      },
      returnAll: true,
    },
    { alwaysOutputData: true, executeOnce: true },
  );
  node('BuildResult', 'Build Preparation Result', 'code', 2, [960, 0], {
    mode: 'runOnceForAllItems',
    jsCode: result,
  });
  node('ReturnEvent', 'Return Domain Event', 'executeWorkflow', 1.3, [1200, 0], {
    source: 'database',
    workflowId: { __rl: true, value: 'frF2jemAeCrcFPDe', mode: 'id' },
    mode: 'each',
    options: { waitForSubWorkflow: false },
  });
  node('Overview', 'Prepare recorded submission', 'stickyNote', 1, [200, -330], {
    content:
      '## Prepare a recorded submission\nThe REGISTERED state starts this task through task_bindings. Read the exact registration event and its pinned machine. Stored published-workflow evidence produces WORKFLOW_LINKED; otherwise PUBLICATION_PENDING.\nReturn one domain event asynchronously to the same generic core, with stable invocation/result IDs. The task never chooses a jury outcome, sends email or issues a PIN. The core rejects results if the case has moved on.',
    width: 1240,
    height: 240,
    color: 5,
  });
  for (const [from, to] of [
    ['ReceiveInvocation', 'ValidateInvocation'],
    ['ValidateInvocation', 'ReadCaseEvents'],
    ['ReadCaseEvents', 'ReadDefinition'],
    ['ReadDefinition', 'BuildResult'],
    ['BuildResult', 'ReturnEvent'],
  ])
    routes.push(`this.${from}.out(0).to(this.${to}.in(0));`);
  let id;
  try {
    id = new WorkflowBuilder().build(await new TypeScriptParser().parseFile(workflowPath)).id;
  } catch {}
  return `// <workflow-map>\n// ReceiveInvocation -> ValidateInvocation -> ReadCaseEvents -> ReadDefinition -> BuildResult -> ReturnEvent (async)\n// </workflow-map>\n// GENERATED by scripts/build-prepare-submission.mjs; edit runtime/prepare-submission-*.js.\nimport {workflow,node,links} from '@n8n-as-code/transformer';\n@workflow(${JSON.stringify({ ...(id ? { id } : {}), name: 'Flow4Gold - Competition - Prepare Submission', active: false, settings: { executionOrder: 'v1' } })})\nexport class PrepareSubmissionWorkflow {\n${nodes.join('\n')}\n@links()\ndefineRouting(){${routes.join('\n')}}\n}`;
}
if (process.argv[1]?.endsWith('/build-prepare-submission.mjs')) {
  const source = await buildSource(),
    parser = new TypeScriptParser(),
    builder = new WorkflowBuilder();
  const expected = builder.build(await parser.parseCode(source));
  if (process.argv.includes('--check')) {
    const actual = builder.build(await parser.parseFile(workflowPath));
    for (const key of ['name', 'nodes', 'connections'])
      if (!isDeepStrictEqual(expected[key], actual[key]))
        throw new Error(`Preparation workflow differs (${key}). Rebuild.`);
    console.log('Submission preparation workflow matches source.');
  } else {
    await writeFile(
      workflowPath,
      await new AstToTypeScriptGenerator().generate(new JsonToAstParser().parse(expected)),
    );
    console.log(`Built ${workflowPath}`);
  }
}
